// Contracts from the ontology: a JSON Schema per entity, built from the Type cells of its field and
// relation rows. JSON Schema is the neutral format: any stack can validate data against it or
// generate types from it, and the approach does not prescribe which.
//
// Type vocabulary (one per Type cell, "optional" may follow any of them):
//   text · integer · integer 0..2 · integer 1.. · number · boolean · date · datetime
//   one of good, worn, damaged          an enumeration
//   ref `ent.title` · refs `ent.title`   a reference to one or to many entities, by ID
const SCALAR = {
  text: { type: "string" },
  number: { type: "number" },
  boolean: { type: "boolean" },
  date: { type: "string", format: "date" },
  datetime: { type: "string", format: "date-time" },
};

// Returns { schema, optional } or { error }.
export function parseType(text, glossary) {
  const m = text.trim().match(/^(.*?)(?:\s+(optional))?$/);
  const t = m[1].trim();
  const optional = Boolean(m[2]);
  if (SCALAR[t]) return { schema: { ...SCALAR[t] }, optional };
  const int = t.match(/^integer(?:\s+(-?\d+)?\.\.(-?\d+)?)?$/);
  if (int) {
    const schema = { type: "integer" };
    if (int[1] !== undefined) schema.minimum = Number(int[1]);
    if (int[2] !== undefined) schema.maximum = Number(int[2]);
    return { schema, optional };
  }
  const oneOf = t.match(/^one of\s+(.+)$/);
  if (oneOf) return { schema: { enum: oneOf[1].split(",").map((v) => v.trim()) }, optional };
  const ref = t.match(/^(refs?)\s+(ent\.[a-z0-9-]+)$/);
  if (ref) {
    if (!glossary.has(ref[2])) return { error: `${ref[2]} is not an entity in the glossary` };
    const one = { type: "string", "x-ont-ref": ref[2] };
    return { schema: ref[1] === "ref" ? one : { type: "array", items: one }, optional };
  }
  return { error: `unknown type "${text}"` };
}

const words = (name) => name.split("-");
const CASES = {
  camel: (n) => words(n).map((w, i) => (i ? w[0].toUpperCase() + w.slice(1) : w)).join(""),
  snake: (n) => words(n).join("_"),
  kebab: (n) => n,
};

// Problems with Type cells, and the schema when there are none.
export function buildContracts(rows, ONT, cfg) {
  const glossary = new Set(Object.keys(ONT));
  const typed = (id) => cfg.contracts.classes.includes(id.split(".")[0]);
  const problems = [];
  const defs = {};
  for (const r of rows) {
    const [cls, entity, ...rest] = r.id.split(".");
    if (cls === "ent") {
      defs[entity] = {
        title: ONT[r.id].name,
        description: ONT[r.id].def,
        "x-ont": r.id,
        type: "object",
        properties: {},
        required: [],
      };
      continue;
    }
    if (!typed(r.id)) {
      if (r.type) problems.push(`${r.id}: only ${cfg.contracts.classes.join(" and ")} rows carry a type`);
      continue;
    }
    if (!r.type) {
      problems.push(`${r.id}: no type`);
      continue;
    }
    const t = parseType(r.type, glossary);
    if (t.error) {
      problems.push(`${r.id}: ${t.error}`);
      continue;
    }
    const def = defs[entity];
    if (!def) continue; // reported by the placement check
    const prop = CASES[cfg.contracts.propertyCase](rest.join("-"));
    def.properties[prop] = { description: ONT[r.id].def, "x-ont": r.id, ...t.schema };
    if (!t.optional) def.required.push(prop);
  }
  const schema = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $comment: "Generated by tools/ont-check/gen-contracts.mjs from the ontology. Do not edit by hand.",
    $defs: defs,
  };
  return { problems, schema };
}

export const renderContracts = (schema) => `${JSON.stringify(schema, null, 2)}\n`;
